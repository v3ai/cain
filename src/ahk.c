/* Windows key remaps + shortcuts through an AutoHotkey v2 script that runs at login. */
#include "cain.h"

#include <stdlib.h>
#include <string.h>

#ifdef _WIN32
#include <windows.h>
#include <shellapi.h>
#endif

/* Keys that extend a selection when Shift is held (Alt+Shift+H -> Shift+Left). */
static const char *const SELECTABLE[] = {
    "left", "right", "up", "down", "home", "end", "pageup", "pagedown", "tab", NULL,
};

/* Shortcuts Windows already provides out of the box: don't rebind them. */
static const char *const NATIVE[][2] = {
    {"switch_windows", "alt+tab"}, {"show_desktop", "super+d"}, {NULL, NULL},
};

static const char *const WM[][2] = {
    {"close_window", "WinClose \"A\""},
    {"minimize", "WinMinimize \"A\""},
    {"toggle_maximize", "ToggleMax()"},
    {"tile_left", "Send \"#{Left}\""},
    {"tile_right", "Send \"#{Right}\""},
    {"show_desktop", "Send \"#d\""},
    {"lock_screen", "DllCall(\"LockWorkStation\")"},
    {NULL, NULL},
};

static const char *FOOTER =
    "\n"
    "ToggleMax() {\n"
    "    try {\n"
    "        if WinGetMinMax(\"A\") = 1\n"
    "            WinRestore \"A\"\n"
    "        else\n"
    "            WinMaximize \"A\"\n"
    "    }\n"
    "}\n"
    "\n"
    "RunCmd(cmd, opts := \"\") {\n"
    "    try Run cmd, , opts\n"
    "    catch as e\n"
    "        MsgBox \"cain could not run:`n\" cmd \"`n`n\" e.Message\n"
    "}\n";

static int in_list(const char *const *list, const char *s)
{
    for (; *list; list++)
        if (streq(*list, s)) return 1;
    return 0;
}

static char *ahk_str(const char *s)
{
    char *a = str_replace(s, "`", "``"), *b = str_replace(a, "\"", "`\"");
    char *r = xprintf("\"%s\"", b);
    free(a);
    free(b);
    return r;
}

typedef struct { Buf *out; StrList seen; } Script;

static void add(Script *s, const char *hotkey, const char *body)
{
    if (sl_has(&s->seen, hotkey)) {
        warn("duplicate Windows hotkey %s skipped", hotkey);
        return;
    }
    sl_push(&s->seen, hotkey);
    buf_addf(s->out, "%s::%s\n", hotkey, body);
}

void ahk_generate(const Manifest *m, Buf *out)
{
    Script s = {out, {0}};
    buf_add(out, "; Generated by cain from cain.json - edit that file and re-run `cain keys`.\n"
                 "#Requires AutoHotkey v2.0\n"
                 "#SingleInstance Force\n"
                 "SendMode \"Input\"\n"
                 "A_MenuMaskKey := \"vkE8\"  ; stops a lone Alt tap from opening menus\n"
                 "\n"
                 "; ---- key remaps\n");

    for (int i = 0; i < m->nremaps; i++) {
        Combo src = m->remaps[i].from, dst = m->remaps[i].to;
        char *send = ahk_send(dst), *body = xprintf("Send \"%s\"", send);
        if (!src.mods) {
            char *k = ahk_key(src.key), *dk = ahk_key(dst.key);
            add(&s, k, dst.mods ? body : dk);   /* plain remap, e.g. CapsLock::Esc */
            free(k);
            free(dk);
        } else {
            char *hk = ahk_hotkey(src);
            add(&s, hk, body);
            free(hk);
            if (!dst.mods && in_list(SELECTABLE, dst.key) && !(src.mods & M_SHIFT)) {
                /* keep Shift working for selection: Alt+Shift+H -> Shift+Left */
                Combo ss = {src.mods | M_SHIFT, src.key}, ds = {M_SHIFT, dst.key};
                char *hk2 = ahk_hotkey(ss), *send2 = ahk_send(ds), *body2 = xprintf("Send \"%s\"", send2);
                add(&s, hk2, body2);
                free(hk2);
                free(send2);
                free(body2);
            }
        }
        free(send);
        free(body);
    }

    buf_add(out, "\n; ---- shortcuts\n");
    for (int i = 0; i < m->nshortcuts; i++) {
        const Shortcut *sc = &m->shortcuts[i];
        for (int k = 0; k < sc->nkeys; k++) {
            Combo c = sc->keys[k];
            char *cs = combo_str(c), *hk = ahk_hotkey(c);
            int native = 0;
            for (int n = 0; NATIVE[n][0]; n++)
                if (streq(NATIVE[n][0], sc->action) && streq(NATIVE[n][1], cs)) native = 1;
            const char *wm = NULL;
            for (int n = 0; WM[n][0]; n++)
                if (streq(WM[n][0], sc->action)) wm = WM[n][1];

            if (native) {
                /* skip */
            } else if (streq(sc->action, "switch_windows")) {
                /* AltTab only works on "LAlt & key" style hotkeys */
                unsigned alt = c.mods & M_ANY_ALT;
                char *key = ahk_key(c.key);
                if (alt && c.mods == alt) {
                    if (alt != M_RALT) { char *h = xprintf("LAlt & %s", key); add(&s, h, "AltTab"); free(h); }
                    if (alt != M_LALT) { char *h = xprintf("RAlt & %s", key); add(&s, h, "AltTab"); free(h); }
                } else {
                    add(&s, hk, "Send \"!{Tab}\"");
                }
                free(key);
            } else if (wm) {
                add(&s, hk, wm);
            } else {
                char *cmd = launch_command(sc, "windows", m);
                if (cmd) {
                    char *q = ahk_str(cmd);
                    /* cain's own tools are console programs: hide their console window */
                    char *body = starts_with(sc->action, "tool:") ? xprintf("RunCmd(%s, \"Hide\")", q)
                                                                  : xprintf("RunCmd(%s)", q);
                    add(&s, hk, body);
                    free(q);
                    free(body);
                    free(cmd);
                }
            }
            free(cs);
            free(hk);
        }
    }
    buf_add(out, FOOTER);
}

static char *startup_dir(void)
{
    const char *appdata = getenv("APPDATA");
    char *base = appdata ? xstrdup(appdata) : expand("~/AppData/Roaming");
    char *dir = path_join(base, "Microsoft/Windows/Start Menu/Programs/Startup");
    free(base);
    return dir;
}

static int ahk_installed(void)
{
    const char *bases[] = {getenv("ProgramFiles"), getenv("LOCALAPPDATA"), NULL};
    const char *subs[] = {"AutoHotkey/v2/AutoHotkey64.exe", "Programs/AutoHotkey/v2/AutoHotkey64.exe"};
    for (int i = 0; i < 2; i++) {
        if (!bases[i]) continue;
        char *p = path_join(bases[i], subs[i]);
        int ok = file_exists(p);
        free(p);
        if (ok) return 1;
    }
    char *w = which("AutoHotkey64");
    if (!w) w = which("AutoHotkey");
    free(w);
    return w != NULL;
}

void ahk_apply(const Manifest *m)
{
    if (!ahk_installed()) {
        StrList ids = {0};
        sl_push(&ids, "AutoHotkey.AutoHotkey");
        winget_install(&ids);
    }
    char *dir = startup_dir(), *script = path_join(dir, "cain.ahk");
    Buf text = {0};
    ahk_generate(m, &text);
    char *crlf = str_replace(buf_str(&text), "\n", "\r\n");
    write_text(script, crlf, 0);
#ifdef _WIN32
    if (!g_dry_run) {
        /* (re)start it now; #SingleInstance replaces the old copy */
        if ((INT_PTR)ShellExecuteA(NULL, "open", script, NULL, NULL, SW_SHOWNORMAL) <= 32)
            warn("couldn't start %s. Is AutoHotkey v2 installed?", script);
    }
#endif
    free(crlf);
    free(script);
    free(dir);
}
