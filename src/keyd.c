/* Linux key remapping through keyd (https://github.com/rvaiya/keyd).
 *
 * keyd works at the kernel input level, so it behaves the same on every distro and
 * on both X11 and Wayland - unlike input-remapper, which the old Mint-only cain used. */
#include "cain.h"

#include <stdlib.h>
#include <string.h>

#define MAX_LAYERS 64

typedef struct { char *name; Buf lines; } Layer;
typedef struct { Layer v[MAX_LAYERS]; int n; } Layers;

static Buf *layer(Layers *ls, const char *name)
{
    for (int i = 0; i < ls->n; i++)
        if (streq(ls->v[i].name, name)) return &ls->v[i].lines;
    if (ls->n == MAX_LAYERS) die("too many keyd layers");
    ls->v[ls->n].name = xstrdup(name);
    memset(&ls->v[ls->n].lines, 0, sizeof(Buf));
    return &ls->v[ls->n++].lines;
}

/* The keyd layer(s) a modifier activates, e.g. alt -> [alt] and [ralt]. */
static int layers_for(unsigned bit, int has_ralt, int has_rctrl, const char *out[2])
{
    switch (bit) {
    case M_LALT: out[0] = "alt"; return 1;
    case M_RALT: out[0] = "ralt"; return 1;
    case M_ALT: out[0] = "alt"; out[1] = "ralt"; return has_ralt ? 2 : 1;
    case M_LCTRL: out[0] = "control"; return 1;
    case M_RCTRL: out[0] = "rctrl"; return 1;
    case M_CTRL: out[0] = "control"; out[1] = "rctrl"; return has_rctrl ? 2 : 1;
    case M_SHIFT: out[0] = "shift"; return 1;
    default: out[0] = "meta"; return 1;  /* super, lsuper, rsuper */
    }
}

/* Add `line` to every combination of layers the modifiers in `mods` (from bit `i` on) map to. */
static void add_combos(Layers *ls, unsigned mods, int i, const char *prefix, const char *line,
                       int has_ralt, int has_rctrl)
{
    while (i < M_COUNT && !(mods & (1u << i))) i++;
    if (i == M_COUNT) {
        buf_addf(layer(ls, prefix), "%s\n", line);
        return;
    }
    const char *opts[2];
    int n = layers_for(1u << i, has_ralt, has_rctrl, opts);
    for (int k = 0; k < n; k++) {
        char *name = *prefix ? xprintf("%s+%s", prefix, opts[k]) : xstrdup(opts[k]);
        add_combos(ls, mods, i + 1, name, line, has_ralt, has_rctrl);
        free(name);
    }
}

void keyd_generate(const Manifest *m, Buf *out)
{
    unsigned used = 0;
    for (int i = 0; i < m->nremaps; i++) used |= m->remaps[i].from.mods;
    /* Split the right-hand modifiers into their own layers only when needed. */
    int has_ralt = (used & M_ANY_ALT) != 0;
    int has_rctrl = (used & (M_LCTRL | M_RCTRL)) != 0;

    Layers ls = {0};
    Buf *main_layer = layer(&ls, "main");
    if (has_ralt) buf_add(main_layer, "rightalt = layer(ralt)\n");
    if (has_rctrl) buf_add(main_layer, "rightcontrol = layer(rctrl)\n");

    for (int i = 0; i < m->nremaps; i++) {
        Remap *r = &m->remaps[i];
        char *outp = keyd_output(r->to);
        char *line = xprintf("%s = %s", keyd_key(r->from.key), outp);
        if (!r->from.mods) buf_addf(main_layer, "%s\n", line);
        else add_combos(&ls, r->from.mods, 0, "", line, has_ralt, has_rctrl);
        free(line);
        free(outp);
    }

    buf_add(out, "# Generated by cain from cain.json - edit that file and re-run `cain keys`.\n\n"
                 "[ids]\n*\n\n");
    for (int i = 0; i < ls.n; i++) {
        if (!ls.v[i].lines.len) continue;
        const char *name = ls.v[i].name;
        const char *header = streq(name, "ralt") ? "ralt:A" : streq(name, "rctrl") ? "rctrl:C" : name;
        buf_addf(out, "[%s]\n%s\n", header, ls.v[i].lines.s);
    }
    if (ends_with(buf_str(out), "\n\n")) out->s[--out->len] = 0;
}

static int install_keyd(const char *pm)
{
    char *found = which("keyd");
    if (found) {
        free(found);
        return 1;
    }
    StrList pkgs = {0};
    sl_push(&pkgs, "keyd");
    if (install_linux_packages(pm, &pkgs, 1)) {
        found = which("keyd");
        free(found);
        if (found || g_dry_run) return 1;
    }
    info("  keyd isn't packaged here, building it from source");
    StrList deps = {0};
    const char *list = streq(pm, "apt") ? "build-essential git"
                     : streq(pm, "pacman") || streq(pm, "xbps") ? "base-devel git"
                     : streq(pm, "apk") ? "build-base git linux-headers"
                     : "gcc make git";
    char *copy = xstrdup(list);
    for (char *t = strtok(copy, " "); t; t = strtok(NULL, " ")) sl_push(&deps, t);
    install_linux_packages(pm, &deps, 0);

    char *src = expand("~/.cache/cain/keyd");
    if (!is_dir(src)) {
        char *parent = path_dir(src);
        mkdirs(parent);
        run(ARGV("git", "clone", "--depth", "1", "https://github.com/rvaiya/keyd", src), 0);
    }
    if (run(ARGV("make", "-C", src), 0) != 0) {
        warn("building keyd failed; key remaps were not installed");
        return 0;
    }
    run(ARGV("make", "-C", src, "install"), RUN_SUDO);
    return 1;
}

void keyd_apply(const Manifest *m, const char *pm)
{
    if (!install_keyd(pm)) return;
    char *state = output(ARGV("systemctl", "is-active", "input-remapper"));
    if (state && starts_with(state, "active")) {
        warn("input-remapper is running and will double-remap keys alongside keyd.");
        if (ask("  Disable input-remapper?", 1))
            run(ARGV("systemctl", "disable", "--now", "input-remapper"), RUN_SUDO);
    }
    Buf conf = {0};
    keyd_generate(m, &conf);
    write_text(KEYD_CONFIG, buf_str(&conf), 1);
    char *systemctl = which("systemctl");
    if (systemctl) run(ARGV("systemctl", "enable", "--now", "keyd"), RUN_SUDO);
    else warn("no systemd found: make sure the keyd daemon starts at boot");
    run(ARGV("keyd", "reload"), RUN_SUDO);
}
