"""Windows key remaps + shortcuts through an AutoHotkey v2 script that runs at login."""

import os
from pathlib import Path

from . import util
from .actions import launch_command
from .keys import ahk_hotkey, ahk_key, ahk_send
from .util import warn, write_text

# Keys that extend a selection when Shift is held (Alt+Shift+H -> Shift+Left).
SELECTABLE = {"left", "right", "up", "down", "home", "end", "pageup", "pagedown", "tab"}

# Shortcuts Windows already provides out of the box: don't rebind them.
NATIVE = {("switch_windows", "alt+tab"), ("show_desktop", "super+d")}

WM = {
    "close_window": 'WinClose "A"',
    "minimize": 'WinMinimize "A"',
    "toggle_maximize": "ToggleMax()",
    "tile_left": 'Send "#{Left}"',
    "tile_right": 'Send "#{Right}"',
    "show_desktop": 'Send "#d"',
    "lock_screen": 'DllCall("LockWorkStation")',
}

FOOTER = """
ToggleMax() {
    try {
        if WinGetMinMax("A") = 1
            WinRestore "A"
        else
            WinMaximize "A"
    }
}

RunCmd(cmd) {
    try Run cmd
    catch as e
        MsgBox "cain could not run:`n" cmd "`n`n" e.Message
}
"""


def ahk_str(s):
    return '"' + s.replace("`", "``").replace('"', '`"') + '"'


def generate(remaps, shortcuts, settings):
    lines = ["; Generated by cain from cain.json - edit that file and re-run `cain keys`.",
             "#Requires AutoHotkey v2.0", "#SingleInstance Force", 'SendMode "Input"',
             'A_MenuMaskKey := "vkE8"  ; stops a lone Alt tap from opening menus', "",
             "; ---- key remaps"]
    seen = set()

    def add(hotkey, body):
        if hotkey in seen:
            warn("duplicate Windows hotkey %s skipped" % hotkey)
            return
        seen.add(hotkey)
        lines.append("%s::%s" % (hotkey, body))

    for src, dst in remaps:
        if not src.mods:
            add(ahk_key(src.key), ahk_key(dst.key) if not dst.mods else 'Send "%s"' % ahk_send(dst))
            continue
        add(ahk_hotkey(src), 'Send "%s"' % ahk_send(dst))
        if not dst.mods and dst.key in SELECTABLE and "shift" not in src.mods:
            # keep Shift working for selection: Alt+Shift+H -> Shift+Left
            add(ahk_hotkey(src.with_mods(src.mods + ("shift",))),
                'Send "%s"' % ahk_send(dst.with_mods(["shift"])))

    lines += ["", "; ---- shortcuts"]
    for sc, combos in shortcuts:
        action = sc["action"]
        for combo in combos:
            if (action, str(combo)) in NATIVE:
                continue
            if action == "switch_windows":
                alts = {"alt": ["LAlt", "RAlt"], "lalt": ["LAlt"], "ralt": ["RAlt"]}
                if combo.mods and combo.mods[0] in alts and len(combo.mods) == 1:
                    for a in alts[combo.mods[0]]:
                        add("%s & %s" % (a, ahk_key(combo.key)), "AltTab")
                else:
                    add(ahk_hotkey(combo), 'Send "!{Tab}"')
            elif action in WM:
                add(ahk_hotkey(combo), WM[action])
            else:
                add(ahk_hotkey(combo), "RunCmd(%s)" % ahk_str(launch_command(sc, "windows", settings)))
    return "\n".join(lines) + "\n" + FOOTER


def startup_dir():
    return Path(os.environ.get("APPDATA", "~")) / "Microsoft/Windows/Start Menu/Programs/Startup"


def apply(remaps, shortcuts, settings):
    from .packages import winget_install
    if not _ahk_installed():
        winget_install(["AutoHotkey.AutoHotkey"])
    script = startup_dir() / "cain.ahk"
    write_text(script, generate(remaps, shortcuts, settings))
    if not util.DRY_RUN:
        try:
            os.startfile(str(script))  # (re)start it now; #SingleInstance replaces the old one
        except OSError as e:
            warn("couldn't start %s (%s). Is AutoHotkey v2 installed?" % (script, e))


def _ahk_installed():
    for base in [os.environ.get("ProgramFiles", ""), os.environ.get("LOCALAPPDATA", "") + "/Programs"]:
        if base and (Path(base) / "AutoHotkey/v2/AutoHotkey64.exe").exists():
            return True
    return bool(util.which("AutoHotkey64") or util.which("AutoHotkey"))
