"""Linux key remapping through keyd (https://github.com/rvaiya/keyd).

keyd works at the kernel input level, so it behaves the same on every distro and on
both X11 and Wayland - unlike input-remapper, which the old Mint-only cain used.
"""

import itertools

from . import util
from .keys import keyd_key, keyd_output
from .util import run, warn, which, write_text, output

CONFIG = "/etc/keyd/default.conf"


def _layers_for(mod, has_ralt, has_rctrl):
    return {
        "lalt": ["alt"], "ralt": ["ralt"], "alt": ["alt"] + (["ralt"] if has_ralt else []),
        "lctrl": ["control"], "rctrl": ["rctrl"],
        "ctrl": ["control"] + (["rctrl"] if has_rctrl else []),
        "super": ["meta"], "lsuper": ["meta"], "rsuper": ["meta"], "shift": ["shift"],
    }[mod]


def generate(remaps):
    mods_used = {m for src, _ in remaps for m in src.mods}
    # Split the right-hand modifiers into their own layers only when needed.
    has_ralt = bool(mods_used & {"alt", "ralt", "lalt"})
    has_rctrl = bool(mods_used & {"rctrl", "lctrl"})

    layers = {"main": []}
    if has_ralt:
        layers["main"].append("rightalt = layer(ralt)")
    if has_rctrl:
        layers["main"].append("rightcontrol = layer(rctrl)")

    for src, dst in remaps:
        line = "%s = %s" % (keyd_key(src.key), keyd_output(dst))
        if not src.mods:
            layers["main"].append(line)
            continue
        options = [_layers_for(m, has_ralt, has_rctrl) for m in src.mods]
        for combo in itertools.product(*options):
            layers.setdefault("+".join(combo), []).append(line)

    headers = {"ralt": "ralt:A", "rctrl": "rctrl:C"}
    out = ["# Generated by cain from cain.json - edit that file and re-run `cain keys`.",
           "", "[ids]", "*", ""]
    for name, lines in layers.items():
        if not lines:
            continue
        out.append("[%s]" % headers.get(name, name))
        out.extend(lines)
        out.append("")
    return "\n".join(out)


def install_keyd(pm):
    if which("keyd"):
        return True
    from .packages import install_linux_packages
    if install_linux_packages(pm, ["keyd"], quiet=True):
        return bool(which("keyd")) or util.DRY_RUN
    util.info("  keyd isn't packaged here, building it from source")
    deps = {"apt": ["build-essential", "git"], "dnf": ["gcc", "make", "git"],
            "pacman": ["base-devel", "git"], "zypper": ["gcc", "make", "git"],
            "apk": ["build-base", "git", "linux-headers"], "xbps": ["base-devel", "git"]}
    install_linux_packages(pm, deps.get(pm, ["gcc", "make", "git"]))
    src = util.tmpdir() / "keyd"
    run(["git", "clone", "--depth", "1", "https://github.com/rvaiya/keyd", str(src)], check=False)
    r = run(["make", "-C", str(src)])
    if not util.ok(r):
        warn("building keyd failed; key remaps were not installed")
        return False
    run(["make", "-C", str(src), "install"], sudo=True)
    return True


def apply(remaps, pm):
    if not install_keyd(pm):
        return
    if output(["systemctl", "is-active", "input-remapper"]).strip() == "active":
        warn("input-remapper is running and will double-remap keys alongside keyd.")
        if util.ask("  Disable input-remapper?"):
            run(["systemctl", "disable", "--now", "input-remapper"], sudo=True)
    write_text(CONFIG, generate(remaps), sudo=True)
    if which("systemctl"):
        run(["systemctl", "enable", "--now", "keyd"], sudo=True)
    else:
        warn("no systemd found: make sure the keyd daemon starts at boot")
    run(["keyd", "reload"], sudo=True)
